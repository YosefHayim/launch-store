/** HTML-comment fences around the managed Launch section in shared consumer docs. */
export const MANAGED_START = '<!-- launch:start -->';
/** Closing fence for the managed Launch section; see {@link MANAGED_START}. */
export const MANAGED_END = '<!-- launch:end -->';

/** Version stamp so `launch agents check` can detect drift without reading git. */
const stamp = (version: string): string =>
  `<!-- generated by launch v${version} - \`npx launch agents init\` - do not hand-edit -->`;

/** Render one recipe step as a code-spanned `npx launch ...` line plus its note. */
const renderStep = (step: SkillStep): string => {
  const commandParts = ['npx', 'launch', ...step.path];
  if (step.args !== undefined) commandParts.push(...step.args);
  return `\`${commandParts.join(' ')}\` - ${step.note}`;
};

/** Render a skill's reference catalog as a two-column markdown table. */
const renderReferenceTable = (commands: readonly SkillStep[]): string => {
  const rows = commands.map((step) => {
    const commandParts = ['npx', 'launch', ...step.path];
    if (step.args !== undefined) commandParts.push(...step.args);
    return `| \`${commandParts.join(' ')}\` | ${step.note} |`;
  });
  return ['| Command | What it does |', '| --- | --- |', ...rows].join('\n');
};

/** Inline command-reference section for targets without progressive disclosure files. */
const renderInlineReference = (skill: ConsumerSkill): string => {
  if (skill.reference === undefined) return '';
  return `## Command reference\n\n${skill.reference.intro}\n\n${renderReferenceTable(skill.reference.commands)}`;
};

/** Bulleted "Use this when" list from a skill's triggers. */
const renderTriggers = (triggers: readonly string[]): string =>
  ['## Use this when', '', ...triggers.map((trigger) => `- ${trigger}`)].join('\n');

/** Numbered recipe for consumer skills (`npx launch ...` lines). */
const renderRecipe = (steps: readonly SkillStep[]): string =>
  ['## Steps', '', ...steps.map((step, stepIndex) => `${stepIndex + 1}. ${renderStep(step)}`)].join(
    '\n',
  );

/** Cautions block, or empty when the skill has none. */
const renderCautions = (cautions: readonly string[] | undefined): string => {
  if (cautions === undefined) return '';
  if (cautions.length === 0) return '';
  return ['## Cautions', '', ...cautions.map((caution) => `- ${caution}`)].join('\n');
};

/** Join non-empty markdown chunks with blank lines, then end with a single trailing newline. */
const joinSections = (sections: readonly string[]): string =>
  `${sections.filter((section) => section.trim() !== '').join('\n\n')}\n`;

/** Wrap managed prose in the Launch start/end fences used by splice. */
const wrapManagedBlock = (sections: readonly string[]): string => {
  const inner = sections.filter((section) => section.trim() !== '').join('\n\n');
  return `${MANAGED_START}\n${inner}\n${MANAGED_END}`;
};

/** EAS -> Launch command map as a markdown table. */
const renderCommandMap = (base: BaseContext): string => {
  const commandMappings = base.commandMap.map(
    (commandMapping) =>
      `| \`${commandMapping.eas}\` | \`${commandMapping.launch}\` | ${commandMapping.note} |`,
  );
  return ['| EAS | Launch | Notes |', '| --- | --- | --- |', ...commandMappings].join('\n');
};

/** Always-on base context sections (shared by Cursor base rules and AGENTS.md). */
const renderBaseSections = (base: BaseContext, headingLevel: number): string[] => {
  const heading = '#'.repeat(headingLevel);
  return [
    base.intro,
    `${heading} EAS -> Launch\n\n${renderCommandMap(base)}`,
    `${heading} Safety rails\n\n${base.rails.map((rail) => `- ${rail}`).join('\n')}`,
    [
      `${heading} What an agent may run vs must confirm`,
      '',
      '**Run freely (idempotent, reversible, or read-only):**',
      '',
      ...base.guardrail.free.map((freeCommand) => `- ${freeCommand}`),
      '',
      '**Confirm with a human first (irreversible / public-facing):**',
      '',
      ...base.guardrail.confirm.map((confirmCommand) => `- ${confirmCommand}`),
    ].join('\n'),
    `${heading} Getting started\n\n${base.bootstrap.map((bootstrapLine) => `- ${bootstrapLine}`).join('\n')}`,
  ];
};

/** Shared body for description-driven task rules across Cursor/Windsurf/Cline/Amazon Q. */
const renderTaskSkillMarkdown = (
  skill: ConsumerSkill,
  version: string,
  leadingSections: readonly string[] = [],
): string =>
  joinSections([
    ...leadingSections,
    `# ${skill.title}`,
    stamp(version),
    renderTriggers(skill.triggers),
    renderRecipe(skill.steps),
    skill.body,
    renderInlineReference(skill),
    renderCautions(skill.cautions),
  ]);

/** Shared always-on base rule (optional frontmatter + Launch base sections). */
const renderBaseRuleMarkdown = (
  version: string,
  base: BaseContext,
  headingLevel: number,
  frontmatter: string | undefined,
): string => {
  const sections: string[] = [];
  if (frontmatter !== undefined) sections.push(frontmatter);
  sections.push('# Launch', stamp(version), ...renderBaseSections(base, headingLevel));
  return joinSections(sections);
};

/**
 * Claude Skill files for one skill: always `SKILL.md`, plus `reference.md` when the skill carries a
 * large catalog (progressive disclosure). Frontmatter is exactly Claude's two trigger fields.
 */
export const renderClaudeSkillFiles = (
  skill: ConsumerSkill,
  version: string,
): GeneratedAgentFile[] => {
  const frontmatter = ['---', `name: ${skill.id}`, `description: ${skill.description}`, '---'].join(
    '\n',
  );
  let referencePointer = '';
  if (skill.reference !== undefined) {
    referencePointer =
      'See [`reference.md`](./reference.md) for the full command surface across both stores.';
  }
  const skillMarkdown = joinSections([
    frontmatter,
    `# ${skill.title}`,
    stamp(version),
    renderTriggers(skill.triggers),
    renderRecipe(skill.steps),
    skill.body,
    referencePointer,
    renderCautions(skill.cautions),
  ]);
  const generatedFiles: GeneratedAgentFile[] = [
    { path: `.claude/skills/${skill.id}/SKILL.md`, body: skillMarkdown },
  ];
  if (skill.reference !== undefined) {
    const referenceMarkdown = joinSections([
      `# ${skill.title} - command reference`,
      stamp(version),
      skill.reference.intro,
      renderReferenceTable(skill.reference.commands),
    ]);
    generatedFiles.push({
      path: `.claude/skills/${skill.id}/reference.md`,
      body: referenceMarkdown,
    });
  }
  return generatedFiles;
};

/** Cursor base rule: `alwaysApply: true` so Cursor always knows Launch is present. */
