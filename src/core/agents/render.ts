/** One skill flattened into an AGENTS.md subsection (Codex has no per-task skill files). */
const renderSkillSection = (skill: ConsumerSkill): string => {
  const parts = [
    `### ${skill.title}`,
    `_Use when: ${skill.triggers.join('; ')}._`,
    skill.steps.map((step, stepIndex) => `${stepIndex + 1}. ${renderStep(step)}`).join('\n'),
    skill.body,
  ];
  if (skill.reference !== undefined) {
    parts.push(
      `**Command reference.** ${skill.reference.intro}`,
      renderReferenceTable(skill.reference.commands),
    );
  }
  if (skill.cautions !== undefined && skill.cautions.length > 0) {
    parts.push(`**Cautions:**\n${skill.cautions.map((caution) => `- ${caution}`).join('\n')}`);
  }
  return parts.filter((part) => part.trim() !== '').join('\n\n');
};

/**
 * Managed Launch section for consumer `AGENTS.md` - base context plus every task recipe flattened.
 * Includes fences so {@link spliceManagedBlock} can replace the region without touching user prose.
 */
export const renderAgentsBlock = (
  version: string,
  base: BaseContext = BASE_CONTEXT,
  skills: readonly ConsumerSkill[] = CONSUMER_SKILLS,
): string =>
  wrapManagedBlock([
    '## Shipping this app with Launch',
    stamp(version),
    ...renderBaseSections(base, 3),
    '### Common tasks',
    skills.map(renderSkillSection).join('\n\n'),
  ]);

/**
 * Managed Launch section for consumer `CLAUDE.md`: import shared `AGENTS.md` and point at Skills.
 * Always-on context lives here; task detail lives under `.claude/skills/`.
 */
export const renderClaudeMemoryBlock = (
  version: string,
  skills: readonly ConsumerSkill[] = CONSUMER_SKILLS,
): string => {
  const skillList = skills.map((skill) => `\`${skill.id}\``).join(', ');
  return wrapManagedBlock([
    '## Launch',
    stamp(version),
    'This repo ships with **Launch** (build, sign & ship to the App Store / Play). The always-on context and the EAS -> Launch map live in `AGENTS.md` - imported here:',
    '@AGENTS.md',
    `Task recipes are Claude Skills under \`.claude/skills/\` (${skillList}); reach for the one matching the request. Before any PUBLIC release (\`launch release\`), credential change, or applying a store reconcile to a live listing, confirm with the developer.`,
  ]);
};

/**
 * Splice a fenced managed block into an existing file, replacing a prior Launch region when present.
 * Empty files become just the block; unfenced content is preserved above an appended block.
 */
export const spliceManagedBlock = (existing: string, blockWithMarkers: string): string => {
  const start = existing.indexOf(MANAGED_START);
  const end = existing.indexOf(MANAGED_END);
  if (start !== -1 && end !== -1 && end > start) {
    return existing.slice(0, start) + blockWithMarkers + existing.slice(end + MANAGED_END.length);
  }
  if (existing.trim() === '') return `${blockWithMarkers}\n`;
  return `${existing.replace(/\n*$/, '')}\n\n${blockWithMarkers}\n`;
};

/** One committed contributor Cursor rule for working ON launch-store (no version stamp - git tracks it). */
export const renderContributorRule = (rule: ContributorRule): GeneratedAgentFile => {
  const frontmatter = ['---', `description: ${rule.description}`];
  if (rule.globs.length > 0) frontmatter.push(`globs: ${rule.globs.join(',')}`);
  frontmatter.push(`alwaysApply: ${rule.alwaysApply}`, '---');
  return {
    path: `.cursor/rules/${rule.file}.mdc`,
    body: `${frontmatter.join('\n')}\n\n${rule.body}\n`,
  };
};

/** Every committed contributor rule (`pnpm docs:gen` / `docs:check`). */
export const renderContributorRules = (
  rules: readonly ContributorRule[] = CONTRIBUTOR_RULES,
): GeneratedAgentFile[] => rules.map(renderContributorRule);

/**
 * One committed contributor Claude skill. Steps are free-form markdown (repo workflow), not
 * `npx launch ...` lines.
 */
export const renderContributorSkill = (skill: ContributorSkill): GeneratedAgentFile => {
  const frontmatter = ['---', `name: ${skill.id}`, `description: ${skill.description}`, '---'].join(
    '\n',
  );
  const recipe = [
    '## Steps',
    '',
    ...skill.steps.map((step, stepIndex) => `${stepIndex + 1}. ${step}`),
  ].join('\n');
  return {
    path: `.claude/skills/${skill.id}/SKILL.md`,
    body: joinSections([
      frontmatter,
      `# ${skill.title}`,
      renderTriggers(skill.triggers),
      recipe,
      skill.body,
      renderCautions(skill.cautions),
    ]),
  };
};

/** Every committed contributor skill (`pnpm docs:gen` / `docs:check`). */
export const renderContributorSkills = (
  skills: readonly ContributorSkill[] = CONTRIBUTOR_SKILLS,
): GeneratedAgentFile[] => skills.map(renderContributorSkill);

