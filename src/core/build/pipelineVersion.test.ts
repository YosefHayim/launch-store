import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { runOnNodePlatform } from '@testkit/platformRun.testkit.js';
import { findNativeTargetDirectory, setNativePlistValue } from './pipelineVersion.js';
/** A minimal generated `Info.plist` - enough for the target probe to recognise the app directory. */
const INFO_PLIST = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleVersion</key>
	<string>1</string>
</dict>
</plist>
`;
/** The regular files `expo prebuild` writes directly into `ios/`, beside the app target. */
const PREBUILD_FILES = ['.gitignore', '.xcode.env', '.xcode.env.local', 'Podfile'];
const scratchDirs: string[] = [];
const makeAppDir = (): string => {
  const appDir = mkdtempSync(join(tmpdir(), 'pipeline-version-test-'));
  scratchDirs.push(appDir);
  return appDir;
};
const writePrebuildFiles = (nativeDirectory: string) => {
  for (const fileName of PREBUILD_FILES) {
    writeFileSync(join(nativeDirectory, fileName), '# generated by expo prebuild\n');
  }
};
/**
 * Lay out an app root whose `ios/` mirrors what `expo prebuild` generates: regular files that sort
 * before the app target on APFS, plus the sibling Xcode directories that carry no `Info.plist`.
 */
const makePrebuiltNativeDir = (targetName: string): string => {
  const nativeDirectory = join(makeAppDir(), 'ios');
  mkdirSync(nativeDirectory);
  writePrebuildFiles(nativeDirectory);
  mkdirSync(join(nativeDirectory, `${targetName}.xcodeproj`));
  mkdirSync(join(nativeDirectory, `${targetName}.xcworkspace`));
  mkdirSync(join(nativeDirectory, targetName));
  writeFileSync(join(nativeDirectory, targetName, 'Info.plist'), INFO_PLIST);
  return nativeDirectory;
};
afterEach(() => {
  for (const appDir of scratchDirs.splice(0)) rmSync(appDir, { recursive: true, force: true });
});
describe('findNativeTargetDirectory', () => {
  it('finds the app target behind the regular files expo prebuild writes beside it', async () => {
    const nativeDirectory = makePrebuiltNativeDir('OLY');
    expect(await runOnNodePlatform(findNativeTargetDirectory(nativeDirectory))).toBe('OLY');
  });

  it('returns null when no directory under the native root carries an Info.plist', async () => {
    const nativeDirectory = join(makeAppDir(), 'ios');
    mkdirSync(nativeDirectory);
    writePrebuildFiles(nativeDirectory);
    mkdirSync(join(nativeDirectory, 'Pods'));
    expect(await runOnNodePlatform(findNativeTargetDirectory(nativeDirectory))).toBeNull();
  });
});
describe('setNativePlistValue', () => {
  it('reports no target instead of failing when the native root holds only regular files', async () => {
    const appDir = makeAppDir();
    mkdirSync(join(appDir, 'ios'));
    writePrebuildFiles(join(appDir, 'ios'));
    const stamping = setNativePlistValue(appDir, 'ios', 'CFBundleVersion', 575);
    expect(await runOnNodePlatform(stamping)).toBe(false);
  });

  it('reports no target when the platform has no native project directory', async () => {
    const stamping = setNativePlistValue(makeAppDir(), 'ios', 'CFBundleVersion', 575);
    expect(await runOnNodePlatform(stamping)).toBe(false);
  });
});
